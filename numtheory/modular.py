from numtheory._validation import ints_only


@ints_only
def extended_gcd(a: int, b: int) -> tuple[int, int, int]:
    '''
    Расширенный алгоритм Евклида: находит НОД и коэффициенты Безу.
    Возвращает такие числа g, x, y, что a * x + b * y = g, где g равен наибольшему общему
    делителю a и b и всегда неотрицателен. Знаки аргументов не влияют на g. Если один аргумент
    равен 0, коэффициент при этом нулевом аргументе равен 0, а при другом равен ±1:
    extended_gcd(a, 0) возвращает (|a|, ±1, 0), а extended_gcd(0, b) возвращает (|b|, 0, ±1).
    Для пары (0, 0) возвращается (0, 0, 0): равенство 0 * 0 + 0 * 0 = 0 выполняется.
    Для нецелого аргумента выбрасывает TypeError.

        Параметры:
            a (int): первое целое число
            b (int): второе целое число

        Возвращаемое значение:
            result (tuple[int, int, int]): тройка (g, x, y), где g = НОД(a, b) и a * x + b * y = g
    '''
    if a == 0 and b == 0:
        return 0, 0, 0

    old_r, r = a, b
    old_x, x = 1, 0
    old_y, y = 0, 1
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_x, x = x, old_x - q * x
        old_y, y = y, old_y - q * y

    if old_r < 0:
        return -old_r, -old_x, -old_y
    return old_r, old_x, old_y


@ints_only
def mod_inverse(a: int, m: int) -> int:
    '''
    Находит число, обратное к a по модулю m, через расширенный алгоритм Евклида.
    Результат x лежит в диапазоне от 0 до m - 1 и удовлетворяет условию a * x mod m = 1.
    Обратное существует, только если a и m взаимно просты. Для отрицательного a используется его
    класс вычетов по модулю m. При m = 1 любые два числа сравнимы, поэтому обратным считается 0,
    как у встроенного pow(a, -1, 1). Если обратного нет (НОД(a, m) не равен 1) или модуль
    меньше 1, выбрасывается ValueError, для нецелого аргумента TypeError.

        Параметры:
            a (int): число, для которого ищется обратное, любое целое
            m (int): модуль, натуральное число

        Возвращаемое значение:
            x (int): обратное к a по модулю m, 0 <= x < m
    '''
    if m < 1:
        raise ValueError(f"модуль должен быть натуральным числом, получено {m}")
    g, x, _ = extended_gcd(a, m)
    if g != 1:
        raise ValueError(f"у {a} нет обратного по модулю {m}: НОД({a}, {m}) равен {g}, а не 1")
    return x % m


@ints_only
def solve_diophantine(a: int, b: int, c: int) -> tuple[int, int, int, int]:
    '''
    Решает линейное диофантово уравнение a * x + b * y = c в целых числах.
    Возвращает общее решение в виде (x0, y0, dx, dy): все решения имеют вид x = x0 + dx * t,
    y = y0 + dy * t для целого t, и других нет. Частное решение строится по расширенному
    алгоритму Евклида, шаги равны dx = |b| / g и dy = -sign(b) * a / g, где g = НОД(a, b),
    поэтому при b не равном 0 шаг dx положителен. Частное решение сдвинуто так, чтобы x0 было
    наименьшим неотрицательным, то есть 0 <= x0 < dx. Если b = 0 (a не равно 0), то
    x однозначно равен c / a, этот случай записывается как (c / a, 0, 0, 1): x не меняется,
    y свободен. Если a = 0 (b не равно 0), то y однозначно равен c / b и результат (0, c / b, 1, 0):
    свободен x. Если c не делится на НОД(a, b), решений нет и выбрасывается ValueError.
    При a = b = 0 тоже выбрасывается ValueError: при c не равном 0 решений нет, а при c = 0
    подходит любая пара и параметризации нет. Для нецелого аргумента выбрасывает TypeError.

        Параметры:
            a (int): коэффициент при x
            b (int): коэффициент при y
            c (int): правая часть уравнения

        Возвращаемое значение:
            result (tuple[int, int, int, int]): набор из четырех чисел (x0, y0, dx, dy), общее решение
            x = x0 + dx * t, y = y0 + dy * t
    '''
    if a == 0 and b == 0:
        if c == 0:
            raise ValueError("при a = b = 0 решением является любая пара (x, y), общего вида с параметром нет")
        raise ValueError(f"уравнение 0 * x + 0 * y = {c} не имеет решений")

    g, x, y = extended_gcd(a, b)
    if c % g != 0:
        raise ValueError(f"уравнение {a} * x + {b} * y = {c} не имеет целых решений: {c} не делится на НОД({a}, {b}) = {g}")

    x0, y0 = x * (c // g), y * (c // g)
    dx, dy = b // g, -(a // g)
    if dx == 0:
        return x0, y0, 0, 1

    if dx < 0:
        dx, dy = -dx, -dy
    t = -(x0 // dx)
    return x0 + dx * t, y0 + dy * t, dx, dy


@ints_only
def crt(remainders: list[int], moduli: list[int]) -> tuple[int, int]:
    '''
    Решает систему сравнений x = r_i (mod m_i) по китайской теореме об остатках.
    Модули не обязаны быть попарно взаимно простыми: сравнения объединяются по одному, и система
    совместна, только если для каждой пары r_i - r_j делится на НОД(m_i, m_j). Результат (x, M)
    описывает все решения: это числа x + M * t для целого t, где M равно НОК всех модулей,
    а x лежит в диапазоне 0 <= x < M. Отрицательные остатки допустимы, остаток приводится
    к классу по модулю. Принимает списки и кортежи. Если длины списков разные, списки пустые,
    какой-либо модуль меньше 1 или система несовместна, выбрасывается ValueError, для нецелого
    аргумента или элемента TypeError.

        Параметры:
            remainders (list[int]): остатки r_i, любые целые числа
            moduli (list[int]): модули m_i, натуральные числа, по одному на каждый остаток

        Возвращаемое значение:
            result (tuple[int, int]): пара (x, M), где M = НОК(m_1, ..., m_n), 0 <= x < M,
            все решения системы это x + M * t
    '''
    if len(remainders) != len(moduli):
        raise ValueError(f"остатков {len(remainders)}, а модулей {len(moduli)}: их должно быть поровну")
    if len(moduli) == 0:
        raise ValueError("система пуста: нужен хотя бы один остаток и один модуль")
    for m in moduli:
        if m < 1:
            raise ValueError(f"модуль должен быть натуральным числом, получено {m}")

    x, step = 0, 1
    for r, m in zip(remainders, moduli):
        g, _, _ = extended_gcd(step, m)
        if (r - x) % g != 0:
            raise ValueError(
                f"система несовместна: x = {r} (mod {m}) противоречит предыдущим сравнениям, "
                f"которые дают x = {x} (mod {step})")
        reduced_modulus = m // g
        t = (r - x) // g * mod_inverse(step // g, reduced_modulus) % reduced_modulus
        x += step * t
        step *= reduced_modulus
        x %= step
    return x, step
